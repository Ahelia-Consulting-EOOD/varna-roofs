function ProjectCard({ project }: { project: ProjectSpec }) {
  const price = formatPrice(project.total_eur);
  return (
    <div className="phase-card">
      <div className="phase-card-head">
        <div className="phase-card-name">{project.name_bg}</div>
        <div className="phase-card-sub">{project.sub_bg}</div>
      </div>
      <div className="phase-price">
        <span className="phase-price-num">{price.eur}</span>
        <span className="phase-price-bgn">({price.bgn})</span>
        <span className="phase-price-vat">без ДДС</span>
      </div>
      <div className="phase-section">
        <div className="lbl">Какво доставяме</div>
        <ul className="phase-list">
          {project.scope_bullets.map((b, i) => <li key={i}>{b}</li>)}
        </ul>
      </div>
      {project.muni_inputs && project.muni_inputs.length > 0 && (
        <div className="phase-section phase-muni">
          <div className="lbl">Какво ни трябва от общината</div>
          <ul className="phase-list">
            {project.muni_inputs.map((b, i) => <li key={i}>{b}</li>)}
          </ul>
        </div>
      )}
      <div className="phase-section">
        <div className="lbl">Резултат</div>
        <p className="phase-result">{project.result_bg}</p>
      </div>
    </div>
  );
}

function formatPrice(eur: number): { eur: string; bgn: string } {
  const eurStr = new Intl.NumberFormat("bg-BG", { style: "currency", currency: "EUR", minimumFractionDigits: 0, maximumFractionDigits: 0 })
    .format(eur)
    .replace(/\s+€/, " €");
  const bgnStr = new Intl.NumberFormat("bg-BG", { style: "currency", currency: "BGN", minimumFractionDigits: 2, maximumFractionDigits: 2 })
    .format(eur * BGN_PER_EUR);
  return { eur: eurStr, bgn: bgnStr };
}
